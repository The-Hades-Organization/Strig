"""Snapshot of the public Python surface: the native stubs verbatim plus the signature of every public
name the pure-Python modules define, in a fixed order.

    python3 scripts/api_snapshot.py --check    fails when api/strig.pyi.snap differs from the sources
    python3 scripts/api_snapshot.py --update   rewrites it

Run from crates/strig-python. Needs only the standard library.
"""

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "python" / "strig"
SNAPSHOT = ROOT / "api" / "strig.pyi.snap"
MODULES = ["__init__.py", "dsl.py", "errors.py"]


def signature(node: ast.AST) -> list[str]:
    """The public header lines of a module: imports of names, `__all__`, classes and functions."""
    lines: list[str] = []
    for child in node.body:  # type: ignore[attr-defined]
        if isinstance(child, (ast.Import, ast.ImportFrom, ast.Assign, ast.AnnAssign)):
            lines.append(ast.unparse(child))
        elif isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if not child.name.startswith("_") or child.name in ("__init__", "__call__"):
                header = ast.unparse(child).split("\n", 1)[0]
                lines.append(header + " ...")
        elif isinstance(child, ast.ClassDef):
            if child.name.startswith("_"):
                continue
            bases = ", ".join(ast.unparse(base) for base in child.bases)
            lines.append(f"class {child.name}({bases}):" if bases else f"class {child.name}:")
            for inner in signature(child):
                lines.append("    " + inner)
            lines.append("    ...")
    return lines


def render() -> str:
    parts = ["# Public surface of the strig Python package, generated by scripts/api_snapshot.py.\n"]
    parts.append("\n# ===== _native.pyi =====\n" + (PACKAGE / "_native.pyi").read_text().rstrip() + "\n")
    for name in MODULES:
        tree = ast.parse((PACKAGE / name).read_text())
        parts.append(f"\n# ===== {name} =====\n" + "\n".join(signature(tree)) + "\n")
    return "".join(parts)


def main() -> int:
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    text = render()
    if mode == "--update":
        SNAPSHOT.parent.mkdir(exist_ok=True)
        SNAPSHOT.write_text(text)
        print("python api snapshot updated")
        return 0
    if mode == "--check":
        committed = SNAPSHOT.read_text() if SNAPSHOT.exists() else ""
        if committed != text:
            print(
                "The public Python surface changed and crates/strig-python/api/strig.pyi.snap was not updated.\n"
                "If the change is intended, run in crates/strig-python:  python3 scripts/api_snapshot.py --update\n"
                "and commit the snapshot. A removal or a rename is a breaking change: list it under Breaking in CHANGELOG.md.",
                file=sys.stderr,
            )
            return 1
        print("python api snapshot matches")
        return 0
    print("usage: api_snapshot.py --check | --update", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
