// O gerador de tipos do catálogo: snapshot do arquivo gerado e um uso tipado que o `tsc` compila.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { Context, Engine } from '../dist/index.js';
import { PermissionClient } from '../dist/client.js';
import { generateTypes, type CatalogInput } from '../dist/types-gen.js';
import { PERMISSION_IDS, isPermissionId, permissionDescription, permissionLabel, type PermissionId } from './fixtures/permissions.generated.js';

const catalog = JSON.parse(readFileSync(new URL('../test/fixtures/catalog.json', import.meta.url), 'utf8')) as CatalogInput;
const SNAPSHOT = new URL('../test/fixtures/permissions.generated.ts', import.meta.url);

let failures = 0;
function test(name: string, fn: () => void) {
  try {
    fn();
    console.log(`ok - ${name}`);
  } catch (error) {
    failures += 1;
    process.exitCode = 1;
    console.log(`not ok - ${name}\n  ${error instanceof Error ? error.stack : error}`);
  }
}

test('types: generated file matches the snapshot and is deterministic', () => {
  const source = generateTypes(catalog);
  assert.equal(source, readFileSync(SNAPSHOT, 'utf8'));
  assert.equal(generateTypes({ permissions: [...catalog.permissions].reverse() }), source);
  assert.ok(source.startsWith('// Generated by strig-types.'));
});

test('types: helpers resolve labels with fallback', () => {
  assert.deepEqual(PERMISSION_IDS, ["it's:odd", 'users:read', 'users:write']);
  assert.equal(isPermissionId('users:read'), true);
  assert.equal(isPermissionId('nope'), false);
  assert.equal(permissionLabel('users:write', 'pt-BR'), 'Editar usuários');
  assert.equal(permissionLabel('users:read', 'es'), 'View users');
  assert.equal(permissionLabel("it's:odd"), "it's:odd");
  assert.equal(permissionDescription('users:write', 'pt-BR'), 'Criar e alterar usuários');
  assert.equal(permissionDescription('users:read'), undefined);
});

test('types: PermissionClient accepts the union and still plain strings', () => {
  const client = new PermissionClient<PermissionId>({} as never);
  const id: PermissionId = 'users:read';
  const typed: (permission: PermissionId | (string & {}), resource: never) => boolean = client.can.bind(client);
  assert.equal(typeof typed, 'function');
  assert.equal(typeof id, 'string');
});

// Compile-time only: tsc checks that the typed engine takes the union and plain strings.
export function typedEngineUsage(engine: Engine<PermissionId>, plain: Engine, context: Context, name: string) {
  const resource = { kind: 'org', id: 'o1', path: [] };
  const subject = { id: 'u1', kind: 'user' } as never;
  engine.check(context, { subject, permission: 'users:read', resource });
  engine.explain(context, { subject, permission: name, resource });
  engine.whoCan(context, 'users:write');
  engine.list(context, subject, 'users:read', 'org');
  plain.decide(context, { subject, permission: name, resource });
}

test('types: Engine<PermissionId> keeps accepting any string', () => {
  assert.equal(typeof typedEngineUsage, 'function');
});

test('types: tsc rejects a typo in the union', () => {
  const dir = mkdtempSync(join(tmpdir(), 'strig-types-'));
  try {
    writeFileSync(join(dir, 'p.ts'), readFileSync(SNAPSHOT, 'utf8'));
    writeFileSync(join(dir, 'a.ts'), "import { permissionLabel } from './p.js';\npermissionLabel('users:reed');\n");
    assert.throws(() => execFileSync('npx', ['tsc', '--noEmit', '--strict', '--module', 'nodenext', join(dir, 'a.ts')], { stdio: 'pipe' }));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

if (failures) process.exitCode = 1;
