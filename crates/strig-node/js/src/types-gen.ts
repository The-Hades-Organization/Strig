/** The slice of a catalog export (`CatalogExport`, JSON) the generator reads. */
export interface CatalogInput {
  permissions: Array<{
    key: string;
    label?: string;
    description?: string;
    labels?: Record<string, string>;
    descriptions?: Record<string, string>;
  }>;
}

const quote = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const byKey = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
const sorted = <T>(entries: Array<[string, T]>) => entries.sort(([a], [b]) => byKey(a, b));

/** Generates the TypeScript source with the permission id union, the metadata constant and typed helpers. Output is sorted, so it is stable. */
export function generateTypes(catalog: CatalogInput): string {
  const permissions = [...catalog.permissions].sort((a, b) => byKey(a.key, b.key));
  const locales = [...new Set(permissions.flatMap((p) => [...Object.keys(p.labels ?? {}), ...Object.keys(p.descriptions ?? {})]))].sort(byKey);
  const union = permissions.length ? permissions.map((p) => `  | ${quote(p.key)}`).join('\n') : '  never';
  const record = (entries: Array<[string, string]>) => (entries.length === 0 ? '{}' : `{ ${sorted(entries).map(([k, v]) => `${quote(k)}: ${quote(v)}`).join(', ')} }`);
  const meta = permissions
    .map((p) => {
      const fields = [`label: ${quote(p.label ?? p.key)}`];
      if (p.description !== undefined) fields.push(`description: ${quote(p.description)}`);
      fields.push(`labels: ${record(Object.entries(p.labels ?? {}))}`);
      fields.push(`descriptions: ${record(Object.entries(p.descriptions ?? {}))}`);
      return `  ${quote(p.key)}: { ${fields.join(', ')} },`;
    })
    .join('\n');
  return `// Generated by strig-types. Do not edit by hand.

export type PermissionId =
${union};

export type PermissionLocale = ${locales.length ? locales.map(quote).join(' | ') : 'never'};

export interface PermissionMeta {
  readonly label: string;
  readonly description?: string;
  readonly labels: Readonly<Partial<Record<PermissionLocale, string>>>;
  readonly descriptions: Readonly<Partial<Record<PermissionLocale, string>>>;
}

export const PERMISSIONS: { readonly [K in PermissionId]: PermissionMeta } = {
${meta}
};

export const PERMISSION_IDS = Object.keys(PERMISSIONS) as PermissionId[];

export function isPermissionId(value: string): value is PermissionId {
  return Object.prototype.hasOwnProperty.call(PERMISSIONS, value);
}

/** Display name in the locale, falling back to the default label. */
export function permissionLabel(id: PermissionId, locale?: PermissionLocale): string {
  const meta: PermissionMeta = PERMISSIONS[id];
  return (locale !== undefined ? meta.labels[locale] : undefined) ?? meta.label;
}

/** Description in the locale, falling back to the default description. */
export function permissionDescription(id: PermissionId, locale?: PermissionLocale): string | undefined {
  const meta: PermissionMeta = PERMISSIONS[id];
  return (locale !== undefined ? meta.descriptions[locale] : undefined) ?? meta.description;
}
`;
}
