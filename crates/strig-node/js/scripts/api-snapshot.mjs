// Snapshot of the public TypeScript surface: every declaration file the package ships, in a fixed order.
// `node scripts/api-snapshot.mjs --check` fails when `api/strig.d.ts.snap` differs from the declarations in
// `dist/`; `node scripts/api-snapshot.mjs --update` rewrites it. Compile the TypeScript first.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dist = new URL('../dist/', import.meta.url);
const snap = new URL('../api/strig.d.ts.snap', import.meta.url);

// index.d.ts is hand-written and copied into dist last, so it is read from where it lives.
const source = (name) => (name === 'index.d.ts' ? new URL('../src/index.d.ts', import.meta.url) : new URL(name, dist));
const files = [...new Set([...readdirSync(dist).filter((name) => name.endsWith('.d.ts')), 'index.d.ts'])].sort();
if (!files.includes('angular.d.ts')) {
  console.error('dist/angular.d.ts is missing: compile the TypeScript and the Angular entry (npm run build:ts) first.');
  process.exit(2);
}
const text =
  '// Public surface of @the-hades-organization/strig, generated by scripts/api-snapshot.mjs.\n' +
  files.map((name) => `\n// ===== ${name} =====\n${readFileSync(source(name), 'utf8').trimEnd()}\n`).join('');

const mode = process.argv[2];
if (mode === '--update') {
  writeFileSync(snap, text);
  console.log(`api snapshot updated: ${files.length} declaration files`);
} else if (mode === '--check') {
  let committed = '';
  try {
    committed = readFileSync(snap, 'utf8');
  } catch {}
  if (committed !== text) {
    console.error(
      'The public JavaScript/TypeScript surface changed and crates/strig-node/js/api/strig.d.ts.snap was not updated.\n' +
        'If the change is intended, run in crates/strig-node/js:  npm run build:ts && node scripts/api-snapshot.mjs --update\n' +
        'and commit the snapshot. A removal or a narrowing is a breaking change: list it under Breaking in CHANGELOG.md.',
    );
    process.exit(1);
  }
  console.log('api snapshot matches');
} else {
  console.error('usage: node scripts/api-snapshot.mjs --check | --update');
  process.exit(2);
}
